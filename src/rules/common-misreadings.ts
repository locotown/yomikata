/**
 * よくある誤読パターン
 *
 * Gemini TTSなどで誤読されやすい漢字・単語を正しい読みに変換するための辞書。
 * ユーザーからの報告（misreadings-log.md）に基づいて追加されます。
 *
 * 注意:
 * - 文脈によって読み方が変わる漢字は、一般的な読み方のみ登録
 * - 読み聞かせ（子供向け物語）に特化した読み方を優先
 */
export const COMMON_MISREADINGS: Record<string, string> = {
  // ─────────────────────────────────────────────
  // 日時関連
  // ─────────────────────────────────────────────
  今日: 'きょう',
  明日: 'あした',
  昨日: 'きのう',
  一昨日: 'おととい',
  明後日: 'あさって',
  今朝: 'けさ',
  今晩: 'こんばん',

  // ─────────────────────────────────────────────
  // 人物・人間関連
  // ─────────────────────────────────────────────
  大人: 'おとな',
  子供: 'こども',

  // ─────────────────────────────────────────────
  // 家族関連
  // ─────────────────────────────────────────────
  お母さん: 'おかあさん',
  お父さん: 'おとうさん',
  お兄さん: 'おにいさん',
  お姉さん: 'おねえさん',
  兄弟: 'きょうだい',
  姉妹: 'しまい',

  // ─────────────────────────────────────────────
  // 友達・人間関係
  // ─────────────────────────────────────────────
  友達: 'ともだち',
  仲間: 'なかま',
  皆: 'みんな',

  // ─────────────────────────────────────────────
  // 動作・状態
  // ─────────────────────────────────────────────
  一緒: 'いっしょ',
  上手: 'じょうず',
  下手: 'へた',
  本当: 'ほんとう',

  // ─────────────────────────────────────────────
  // 場所
  // ─────────────────────────────────────────────
  部屋: 'へや',
  玄関: 'げんかん',

  // ─────────────────────────────────────────────
  // その他のよくある誤読
  // ─────────────────────────────────────────────
  凸凹道: 'でこぼこみち',
};

/**
 * よくある誤読を修正する
 *
 * @param text - 変換元のテキスト
 * @returns 変換後のテキスト
 */
export function applyCommonMisreadings(text: string): string {
  let result = text;

  // 長いキーから順に置換（最長一致）
  const sortedKeys = Object.keys(COMMON_MISREADINGS).sort(
    (a, b) => b.length - a.length
  );

  for (const key of sortedKeys) {
    const value = COMMON_MISREADINGS[key];
    // 正規表現の特殊文字をエスケープ
    const escapedKey = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    result = result.replace(new RegExp(escapedKey, 'g'), value);
  }

  return result;
}
